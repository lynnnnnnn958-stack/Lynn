# Earnings blackout filter
# ─────────────────────────────────────────────────────────────────────────────

def get_earnings_blackout_tickers() -> set[str]:
    """Return set of tickers with earnings within EARNINGS_BLACKOUT_DAYS trading days."""
    cal_path = ROOT / "earnings_calendar.csv"
    if not cal_path.exists():
        return set()
    try:
        df = pd.read_csv(cal_path, parse_dates=["earnings_date"])
        if "ticker" not in df.columns or "earnings_date" not in df.columns:
            return set()
        today_dt = pd.Timestamp(TODAY)
        # include today and next N trading days (approx as calendar days × 1.4)
        window_end = today_dt + pd.Timedelta(days=int(EARNINGS_BLACKOUT_DAYS * 1.4) + 1)
        mask = (df["earnings_date"] >= today_dt) & (df["earnings_date"] <= window_end)
        blackout = set(df.loc[mask, "ticker"].dropna().tolist())
        if blackout:
            log(f"  Earnings blackout ({EARNINGS_BLACKOUT_DAYS}d): {', '.join(sorted(blackout)[:8])}"
                f"{'…' if len(blackout)>8 else ''}")
        return blackout
    except Exception:
        return set()


# ─────────────────────────────────────────────────────────────────────────────
# Regime-conditional capital scaling
# ─────────────────────────────────────────────────────────────────────────────

def get_regime_scale() -> float:
    """Read current HMM regime and return capital scale factor."""
    macro_path = ROOT / "macro_signals.json"
    if not macro_path.exists():
        return 1.0
    try:
        macro = json.loads(macro_path.read_text())
        regime = macro.get("hmm_regime", "BULL").upper()
        # Map HMM output to our regime keys
        if "BEAR" in regime or "RISK_OFF" in regime:
            key = "BEAR"
        elif "LATE" in regime:
            key = "LATE_BULL"
        else:
            key = "BULL"
        scale = REGIME_SCALE.get(key, 1.0)
        log(f"  Regime: {regime} → capital scale {scale:.0%}")
        return scale
    except Exception:
        return 1.0


# ─────────────────────────────────────────────────────────────────────────────
# Conviction-weighted position sizing
# ─────────────────────────────────────────────────────────────────────────────

def conviction_weights(scores: pd.Series, n: int, cap: float) -> dict[str, float]:
    """
    Given top-N scores (higher = better), compute conviction weights that
    allocate more capital to higher-ranked picks.

    Uses a linear ramp: rank 1 → TOP_WEIGHT_MULT × equal, rank N → 1/TOP_WEIGHT_MULT × equal.
    Normalises so weights sum to 1, then applies position cap.
    """
    top = scores.nlargest(n)
    tickers = top.index.tolist()
    n_actual = len(tickers)
    if n_actual == 0:
        return {}

    mult = CONVICTION_WEIGHT_MULT
    # raw weights: linearly spaced from mult down to 1/mult
    raw = [mult - (mult - 1.0 / mult) * i / max(n_actual - 1, 1)
           for i in range(n_actual)]
    total_raw = sum(raw)
    weights   = {tk: raw[i] / total_raw for i, tk in enumerate(tickers)}

    # apply position cap
    weights = {tk: min(w, cap) for tk, w in weights.items()}
    # renormalise
    total_w = sum(weights.values())
    if total_w > 0:
        weights = {tk: w / total_w for tk, w in weights.items()}

    return weights


