def cancel_stale_orders(client) -> int:
    """
    Cancel any open limit orders that are more than 1 trading day old.
    Returns count of cancelled orders.
    """
    try:
        from alpaca.trading.requests import GetOrdersRequest
        from alpaca.trading.enums import QueryOrderStatus
        req = GetOrdersRequest(status=QueryOrderStatus.OPEN, limit=200)
        open_orders = client.get_orders(req)
    except Exception as e:
        warn(f"  Could not fetch open orders: {e}")
        return 0

    cancelled = 0
    cutoff = NOW - pd.Timedelta(hours=26)   # >1 trading day old
    for o in open_orders:
        try:
            created = pd.Timestamp(o.created_at)
            if created < cutoff:
                client.cancel_order_by_id(o.id)
                log(f"  Cancelled stale order: {o.side.value} {o.symbol} (age {(NOW-created).days}d)")
                cancelled += 1
        except Exception:
            pass

    if cancelled:
        warn(f"  Cancelled {cancelled} stale unfilled orders")
    else:
        ok(f"  No stale orders to cancel ({len(open_orders)} open orders reviewed)")
    return cancelled


def get_fill_rate(client, lookback_days: int = 5) -> dict[str, float]:
    """Return fill rate per side over last N days."""
    try:
        from alpaca.trading.requests import GetOrdersRequest
        from alpaca.trading.enums import QueryOrderStatus
        since = (NOW - pd.Timedelta(days=lookback_days)).isoformat() + "Z"
        req = GetOrdersRequest(status=QueryOrderStatus.ALL, after=since, limit=500)
        orders = client.get_orders(req)
        total = len(orders)
        filled = sum(1 for o in orders if o.status.value in ("filled", "partially_filled"))
        return {"total": total, "filled": filled,
                "fill_rate": round(filled / max(total, 1), 3)}
    except Exception:
        return {"total": 0, "filled": 0, "fill_rate": 0.0}


