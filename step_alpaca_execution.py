def load_scores(book_name: str) -> pd.Series | None:
    cfg = BOOKS[book_name]
    fpath = ROOT / cfg["score_file"]
    if not fpath.exists():
        warn(f"  Score file missing: {cfg['score_file']}")
        return None

    try:
        df = pd.read_csv(fpath)
    except Exception as e:
        err(f"  Cannot read {cfg['score_file']}: {e}")
        return None

    col = cfg["score_col"]
    if "ticker" not in df.columns or col not in df.columns:
        warn(f"  Missing columns in {cfg['score_file']} — need ticker,{col}")
        return None

    scores = df.set_index("ticker")[col].dropna()
    return scores


# ─────────────────────────────────────────────────────────────────────────────
# Rebalance one book
# ─────────────────────────────────────────────────────────────────────────────

def rebalance_book(
    book_name: str,
    client,
    state: dict,
    total_equity: float,
    regime_scale: float,
    earnings_blackout: set[str],
):
    cfg = BOOKS[book_name]
    hdr(f"  Book: {book_name}")

    # 1. Load scores → apply earnings filter → pick top N
    scores = load_scores(book_name)
    if scores is None or len(scores) < cfg["n_picks"]:
        warn(f"  Insufficient scores for {book_name}")
        return

    # Earnings blackout filter (SHORT book only by default)
    if cfg.get("earnings_filter", False) and earnings_blackout:
        n_before = len(scores)
        scores = scores[~scores.index.isin(earnings_blackout)]
        n_filtered = n_before - len(scores)
        if n_filtered:
            log(f"  Earnings filter removed {n_filtered} tickers from SHORT candidates")

    if len(scores) < cfg["n_picks"]:
        warn(f"  Not enough scores after earnings filter — skipping")
        return

    is_long_short = cfg.get("long_short", False)

    if is_long_short:
        # ── True long/short book (SHORT book) ─────────────────────────────
        # Long leg: top N by score (after earnings filter already applied above)
        long_weights = conviction_weights(scores, cfg["n_picks"], cfg["position_cap"])
        # Short leg: bottom N by score (lowest scores = weakest stocks)
        short_scores = scores.copy()
        # Exclude long candidates from short pool
        short_scores = short_scores[~short_scores.index.isin(long_weights.keys())]
        short_weights_raw = conviction_weights(
            short_scores.sort_values().head(cfg["n_picks"]),  # lowest scores first
            cfg["n_picks"], cfg["position_cap"]
        )

        long_tickers  = list(long_weights.keys())
        short_tickers = list(short_weights_raw.keys())
        all_target_tickers = long_tickers + short_tickers
        log(f"  L/S: LONG {', '.join(long_tickers[:3])}… SHORT {', '.join(short_tickers[:3])}…")

        prices = get_latest_prices(client, all_target_tickers)
        valid_longs  = [tk for tk in long_tickers  if tk in prices and prices[tk] > 0]
        valid_shorts = [tk for tk in short_tickers if tk in prices and prices[tk] > 0]

        if not valid_longs and not valid_shorts:
            warn("  No valid prices — skipping")
            return

        # Normalise weights
        def _norm(wts, valid):
            w = {tk: wts[tk] for tk in valid if tk in wts}
            tot = sum(w.values())
            return {tk: v / tot for tk, v in w.items()} if tot > 0 else {}

        lw = _norm(long_weights, valid_longs)
        sw = _norm(short_weights_raw, valid_shorts)

        effective_capital_pct = cfg["capital_pct"] * regime_scale
        book_capital = total_equity * effective_capital_pct
        half_cap = book_capital * 0.5   # 50% long / 50% short
        log(f"  Capital: ${book_capital:,.0f} ({effective_capital_pct:.0%}) — "
            f"${half_cap:,.0f} each leg")

        # Target dollar values: positive = long, negative = short
        target_values = {}
        for tk, w in lw.items():
            target_values[tk] = half_cap * w          # positive → buy
        for tk, w in sw.items():
            target_values[tk] = -half_cap * w         # negative → short sell

        all_positions = get_positions(client)
        current_book_tickers = set(state.get(book_name, {}).get("positions", {}).keys())

        # Close positions no longer in target
        to_close = current_book_tickers - set(target_values.keys())
        for tk in to_close:
            if tk in all_positions and tk in prices:
                mv = all_positions[tk]   # positive = long, negative = short
                qty = abs(mv) / prices[tk]
                side = "sell" if mv > 0 else "buy"  # close long=sell, close short=buy
                place_limit_order(client, tk, qty, side, prices[tk])

        # Adjust to target
        for tk, tgt_val in target_values.items():
            price   = prices.get(tk, 0)
            if price <= 0:
                continue
            cur_val = all_positions.get(tk, 0.0)
            delta   = tgt_val - cur_val
            if abs(delta) < book_capital * 0.01:
                continue
            qty  = abs(delta) / price
            side = "buy" if delta > 0 else "sell"
            place_limit_order(client, tk, qty, side, price)

        state[book_name]["positions"]        = {tk: v for tk, v in target_values.items()}
        state[book_name]["last_rebalance"]   = NOW.isoformat()
        state[book_name]["regime_scale"]     = regime_scale
        state[book_name]["effective_capital"]= round(book_capital, 2)
        state[book_name]["long_tickers"]     = valid_longs
        state[book_name]["short_tickers"]    = valid_shorts

        ok(f"  SHORT book L/S rebalanced — {len(valid_longs)} long + {len(valid_shorts)} short, "
           f"${book_capital:,.0f}")

    else:
        # ── Long-only books (MEDIUM / LONG) ───────────────────────────────
        weights = conviction_weights(scores, cfg["n_picks"], cfg["position_cap"])
        target_tickers = list(weights.keys())
        log(f"  Top picks: {', '.join(target_tickers[:5])} … "
            f"(conviction spread: {min(weights.values())*100:.1f}%–{max(weights.values())*100:.1f}%)")

        prices = get_latest_prices(client, target_tickers)
        valid_tickers = [tk for tk in target_tickers if tk in prices and prices[tk] > 0]
        if not valid_tickers:
            warn("  No valid prices found — skipping")
            return

        valid_w = {tk: weights[tk] for tk in valid_tickers}
        total_w = sum(valid_w.values())
        if total_w > 0:
            valid_w = {tk: w / total_w for tk, w in valid_w.items()}

        effective_capital_pct = cfg["capital_pct"] * regime_scale
        book_capital = total_equity * effective_capital_pct
        log(f"  Capital: ${book_capital:,.0f} ({effective_capital_pct:.0%} × regime {regime_scale:.0%})")

        target_values = {tk: book_capital * w for tk, w in valid_w.items()}

        all_positions = get_positions(client)
        current_book_tickers = set(state.get(book_name, {}).get("positions", {}).keys())

        to_sell = current_book_tickers - set(valid_tickers)
        for tk in to_sell:
            if tk in all_positions and tk in prices:
                mv  = all_positions[tk]
                qty = mv / prices[tk]
                place_limit_order(client, tk, qty, "sell", prices[tk])

        for tk in valid_tickers:
            price     = prices[tk]
            tgt_val   = target_values[tk]
            cur_val   = all_positions.get(tk, 0.0)
            delta_val = tgt_val - cur_val
            if abs(delta_val) < book_capital * 0.01:
                continue
            qty  = abs(delta_val) / price
            side = "buy" if delta_val > 0 else "sell"
            place_limit_order(client, tk, qty, side, price)

        state[book_name]["positions"]        = {tk: target_values[tk] for tk in valid_tickers}
        state[book_name]["last_rebalance"]   = NOW.isoformat()
        state[book_name]["regime_scale"]     = regime_scale
        state[book_name]["effective_capital"]= round(book_capital, 2)

        ok(f"  {book_name} rebalanced — {len(valid_tickers)} positions, "
           f"${book_capital:,.0f} (regime-adjusted)")


