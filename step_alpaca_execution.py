def main():
    print(f"\n{BOLD}Canyon — Alpaca Execution{'  [PAPER]' if PAPER_TRADING_ONLY else '  ⚠ LIVE'}{RESET}  {TODAY}")

    # Load .env
    env_file = ROOT / ".env"
    if env_file.exists():
        for line in env_file.read_text().splitlines():
            line = line.strip()
            if line and not line.startswith("#") and "=" in line:
                k, v = line.split("=", 1)
                if k.strip() and v.strip() and k.strip() not in os.environ:
                    os.environ[k.strip()] = v.strip()

    client = get_client()
    if client is None:
        return

    total_equity = get_equity(client)
    if total_equity <= 0:
        err("Cannot read account equity")
        return

    state = load_state()

    # Check if market is open
    try:
        clock = client.get_clock()
        if not clock.is_open:
            warn(f"Market is closed (next open: {clock.next_open})")
            warn("Showing current state without placing orders.")
            print_book_report(state, client)
            return
    except Exception:
        warn("Could not check market hours — proceeding anyway")

    # Compute shared inputs once
    regime_scale      = get_regime_scale()
    earnings_blackout = get_earnings_blackout_tickers()
    log(f"  Earnings blackout pool: {len(earnings_blackout)} tickers")

    # Rebalance books that are due
    for book_name in BOOKS:
        if should_rebalance(book_name, state):
            rebalance_book(book_name, client, state, total_equity,
                           regime_scale, earnings_blackout)
        else:
            last = state.get(book_name, {}).get("last_rebalance", "never")
            log(f"  {book_name}: not due for rebalance yet (last: {str(last)[:10]})")

    save_state(state)
    ok("Book state saved → alpaca_book_state.json")

    print_book_report(state, client)
    print(f"\n{GREEN}✓ Alpaca execution complete{RESET}\n")


if __name__ == "__main__":
    main()
