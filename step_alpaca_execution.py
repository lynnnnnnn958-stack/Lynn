def get_client():
    try:
        from alpaca.trading.client import TradingClient
    except ImportError:
        err("alpaca-py not installed — run: pip install alpaca-py")
        return None

    key    = os.environ.get("ALPACA_KEY_ID", "")
    secret = os.environ.get("ALPACA_KEY_SECRET", "")
    if not key or not secret:
        err("ALPACA_KEY_ID / ALPACA_KEY_SECRET not set — check .env")
        return None

    try:
        client = TradingClient(key, secret, paper=PAPER_TRADING_ONLY)
        account = client.get_account()
        mode = "PAPER" if PAPER_TRADING_ONLY else "LIVE"
        ok(f"Alpaca {mode} account — equity: ${float(account.equity):,.0f}  "
           f"buying power: ${float(account.buying_power):,.0f}")
        return client
    except Exception as e:
        err(f"Alpaca connection failed: {e}")
        return None


def get_equity(client) -> float:
    try:
        return float(client.get_account().equity)
    except Exception:
        return 0.0


def get_positions(client) -> dict[str, float]:
    """Returns {ticker: market_value}"""
    try:
        positions = client.get_all_positions()
        return {p.symbol: float(p.market_value) for p in positions}
    except Exception:
        return {}


def get_latest_prices(client, tickers: list[str]) -> dict[str, float]:
    """Returns {ticker: last_price} via Alpaca data API."""
    try:
        from alpaca.data.historical import StockHistoricalDataClient
        from alpaca.data.requests import StockLatestTradeRequest

        key    = os.environ.get("ALPACA_KEY_ID", "")
        secret = os.environ.get("ALPACA_KEY_SECRET", "")
        data_client = StockHistoricalDataClient(key, secret)

        # batch in chunks of 50
        prices = {}
        for i in range(0, len(tickers), 50):
            batch = tickers[i:i+50]
            try:
                req = StockLatestTradeRequest(symbol_or_symbols=batch)
                resp = data_client.get_stock_latest_trade(req)
                for sym, trade in resp.items():
                    prices[sym] = float(trade.price)
            except Exception:
                pass
        return prices
    except Exception:
        return {}


def place_limit_order(client, ticker: str, qty: float, side: str, price: float) -> bool:
    """Place a limit order. side = 'buy' or 'sell'."""
    try:
        from alpaca.trading.requests import LimitOrderRequest
        from alpaca.trading.enums import OrderSide, TimeInForce

        if qty < 0.001:
            return False

        limit_price = round(price * (1.002 if side == "buy" else 0.998), 2)  # 0.2% slippage buffer
        req = LimitOrderRequest(
            symbol=ticker,
            qty=qty,
            side=OrderSide.BUY if side == "buy" else OrderSide.SELL,
            time_in_force=TimeInForce.DAY,
            limit_price=limit_price,
        )
        order = client.submit_order(req)
        log(f"  ORDER {side.upper()} {qty:.4f}×{ticker} @ ${limit_price:.2f}  id={order.id}")
        _log_order(ticker, side, qty, limit_price, order.id)
        return True
    except Exception as e:
        warn(f"  Order failed {ticker}: {e}")
        return False


def _log_order(ticker, side, qty, price, order_id):
    row = pd.DataFrame([{
        "date": TODAY,
        "time": NOW.strftime("%H:%M:%S"),
        "ticker": ticker,
        "side": side,
        "qty": qty,
        "price": price,
        "order_id": str(order_id),
    }])
    if ORDERS_PATH.exists():
        row.to_csv(ORDERS_PATH, mode="a", header=False, index=False)
    else:
        row.to_csv(ORDERS_PATH, index=False)


