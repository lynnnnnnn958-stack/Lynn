def print_book_report(state: dict, client):
    hdr("Portfolio Status")
    all_pos = get_positions(client)
    total_mv = sum(all_pos.values())

    for book_name in BOOKS:
        book_state = state.get(book_name, {})
        last_reb   = book_state.get("last_rebalance", "never")
        positions  = book_state.get("positions", {})
        book_mv    = sum(all_pos.get(tk, 0) for tk in positions)
        print(f"\n  {BOLD}{book_name}{RESET}")
        print(f"    Last rebalance : {last_reb[:10] if last_reb != 'never' else 'never'}")
        print(f"    Positions      : {len(positions)}")
        print(f"    Market value   : ${book_mv:,.0f}")
        if positions:
            print(f"    Holdings       : {', '.join(list(positions.keys())[:8])}{'…' if len(positions)>8 else ''}")

    print(f"\n  Total portfolio value: ${total_mv:,.0f}")


